import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { askErrorMessage } from "../src/utils/ask-safety.js";

// Player-facing copy names the product "Ask Keir". Plain "Ask" stays only as a
// verb ("Ask a question") and in internal ids, env vars and error logs.
const PLAYER_FACING = [
  "src/commands/ask.ts",
  "src/commands/ask-watches.ts",
  "src/utils/ask-charts.ts",
  "src/utils/ask-presentation.ts",
  "src/utils/ask-runtime.ts",
  "src/utils/ask-safety.ts",
  "src/utils/ask-watches.ts",
  "src/utils/helpRegistry.ts",
];
const OLD_NAME = /(Generated by|Report an|Your|the|this|today's|How) Ask\b(?! Keir)|"Ask (is|isn't|could|watches|and Community)\b|`Ask works|Ask's|\*\*Ask watch/;

describe("Ask Keir branding", () => {
  for (const file of PLAYER_FACING) {
    it(`${file} uses Ask Keir in player-facing copy`, () => {
      const offending = readFileSync(file, "utf8")
        .split("\n")
        .filter((line) => !/^\s*(\/\/|\/?\*)/.test(line) && !/throw new Error/.test(line))
        .filter((line) => OLD_NAME.test(line));
      expect(offending).toEqual([]);
    });
  }

  it("names Ask Keir in the chart footer and the generic error", () => {
    expect(readFileSync("src/utils/ask-charts.ts", "utf8")).toContain('const FOOTER = "Generated by Ask Keir";');
    expect(askErrorMessage(new Error("boom"))).toMatch(/^Ask Keir could not answer/);
  });
});
