export function chamberHeight(partyCount: number, shape: ChamberShape, spec: Pick<CardSpec, "subtitle">): number {
  const legendRows = Math.ceil(Math.max(1, partyCount) / LEGEND_COLS);
  const body = shape === "westminster" ? 250 : 226;
  return Math.round(
    chromeHeight({ ...spec, footerLeft: " " }) + HEADER_H + body + legendRows * LEGEND_ROW_H + LEGEND_GAP + PAD * 2,
  );
}

/**
 * Render a chamber card.
 *
 * Async because the Westminster path rasterises an SVG; the arch path draws
 * directly. Both go through the same card chrome.
 */
export async function renderChamber(options: ChamberOptions): Promise<Buffer> {
  const parties = options.parties.filter((p) => p.seats > 0);
  const shape = options.shape ?? "arch";
  const width = options.width ?? 680;
  const height = chamberHeight(parties.length, shape, options);

  const drawn = parties.reduce((s, p) => s + p.seats, 0);
  const total = Math.max(options.totalSeats, drawn);

  // Rasterise before entering the synchronous card renderer.
  const benchImage =
    shape === "westminster" && parties.length > 0
      ? await renderWestminsterImage(buildWestminsterParliament(parties, total, options.governmentPartyNames), 1400)
      : null;

  return renderCard({ ...options, width, height }, (ctx, plot) => {
    if (parties.length === 0) {
      drawEmptyState(ctx, plot, options.emptyMessage ?? "No seat data for this chamber.");
      return;
    }
    draw(ctx, plot, parties, shape, total, benchImage, options);
  });
}

function draw(
  ctx: CanvasRenderingContext2D,
  plot: Rect,
  parties: ChamberParty[],
  shape: ChamberShape,
  total: number,
  benchImage: Image | null,
  options: ChamberOptions,
): void {
  const majority = options.majority ?? Math.floor(total / 2) + 1;
  const { government, opposition } = splitBenches(parties, options.governmentPartyNames);
  const govSeats = government.reduce((s, p) => s + p.seats, 0);
  const oppSeats = opposition.reduce((s, p) => s + p.seats, 0);
  const clears = govSeats >= majority;

  const legendRows = Math.ceil(parties.length / LEGEND_COLS);
  const area: Rect = {
    x: plot.x + PAD,
    y: plot.y + PAD + HEADER_H,
    w: plot.w - PAD * 2,
    h: plot.h - PAD * 2 - HEADER_H - legendRows * LEGEND_ROW_H - LEGEND_GAP,
  };

  if (shape === "westminster") {
    drawWestminster(ctx, area, benchImage);
  } else {
    drawArch(ctx, area, parties, total, majority);
  }

  drawHeader(ctx, plot, { govSeats, oppSeats, total, clears });
  drawVerdict(ctx, plot, area, shape, { clears, majority, govSeats });
  drawLegend(ctx, plot, parties, total, legendRows);
}

/** Composite the rasterised chamber, letterboxed into the plot area. */
function drawWestminster(ctx: CanvasRenderingContext2D, area: Rect, image: Image | null): void {
  if (!image || !image.width || !image.height) {
    drawEmptyState(ctx, area, "Chamber diagram unavailable.");
    return;
  }
  const scale = Math.min(area.w / image.width, area.h / image.height);
  const w = image.width * scale;
  const h = image.height * scale;
  ctx.drawImage(image, area.x + (area.w - w) / 2, area.y + (area.h - h) / 2, w, h);
}

/** Hemicycle, drawn natively so it stays crisp and picks up the house style. */
function drawArch(
  ctx: CanvasRenderingContext2D,
  area: Rect,
  parties: ChamberParty[],
  total: number,
  majority: number,
): void {
  const { seats, outerR } = archLayout(total);
  if (seats.length === 0) return;

  // Game space is 400 wide, centred on (200, 195); fit that arc into the plot.
  const scale = Math.min(area.w / (outerR * 2 + 12), area.h / (outerR + 12));
  const cx = area.x + area.w / 2;
  const cy = area.y + (area.h + outerR * scale) / 2;
  const px = (x: number) => cx + (x - 200) * scale;
  const py = (y: number) => cy + (y - 195) * scale;
  const dotR = Math.max(1, getParliamentSizing(total).dotR * scale * 0.92);

  const colors: string[] = [];
  for (const party of [...parties].sort((a, b) => b.seats - a.seats)) {
    const color = ensureVisible(party.color);
    for (let i = 0; i < party.seats; i++) colors.push(color);
  }

  seats.forEach((seat, i) => {
    ctx.beginPath();
    ctx.arc(px(seat.x), py(seat.y), dotR, 0, Math.PI * 2);
    ctx.fillStyle = colors[i] ?? VACANT;
    ctx.fill();
  });

  // The half-way line, as the game draws it
  ctx.strokeStyle = AXIS.baseline;
  ctx.lineWidth = 1;
  ctx.setLineDash([4, 3]);
  ctx.beginPath();
  ctx.moveTo(cx, py(195 - outerR) - 8);
  ctx.lineTo(cx, py(195) + 2);
  ctx.stroke();
  ctx.setLineDash([]);

  // Ring the seat where the majority actually falls
  const marker = seats[Math.min(seats.length - 1, majority - 1)];
  if (marker) {
    ctx.strokeStyle = alpha(INK.primary, 0.6);
    ctx.lineWidth = 1.4;
    ctx.beginPath();
    ctx.arc(px(marker.x), py(marker.y), dotR + 3.5, 0, Math.PI * 2);
    ctx.stroke();
  }

  ctx.font = font(500, 9, "mono");
  ctx.fillStyle = INK.muted;
  ctx.textAlign = "left";
  ctx.fillText("◄ LEFT", area.x, py(195) + 10);
  ctx.textAlign = "right";
  ctx.fillText("RIGHT ►", area.x + area.w, py(195) + 10);
  ctx.textAlign = "left";
}

function drawHeader(
  ctx: CanvasRenderingContext2D,
  plot: Rect,
  d: { govSeats: number; oppSeats: number; total: number; clears: boolean },
): void {
  const x0 = plot.x + PAD;
  const x1 = plot.x + plot.w - PAD;
  const y = plot.y + PAD;

  ctx.font = font(600, 9.5, "mono");
  ctx.fillStyle = INK.muted;
  ctx.textAlign = "left";
  ctx.fillText(d.clears ? "GOVERNMENT" : "LARGEST PARTY", x0, y + 9);
  ctx.textAlign = "right";
  ctx.fillText(d.clears ? "OPPOSITION" : "OTHER PARTIES", x1, y + 9);

  ctx.font = font(700, 22, "mono");
  ctx.fillStyle = INK.primary;
  ctx.textAlign = "left";
  ctx.fillText(String(d.govSeats), x0, y + 33);
  ctx.textAlign = "right";
  ctx.fillText(String(d.oppSeats), x1, y + 33);

  ctx.font = font(500, 9, "mono");
  ctx.fillStyle = INK.muted;
  ctx.textAlign = "left";
  ctx.fillText(`of ${d.total}`, x0, y + 45);
  ctx.textAlign = "right";
  ctx.fillText(`of ${d.total}`, x1, y + 45);
  ctx.textAlign = "left";
}

function drawVerdict(
  ctx: CanvasRenderingContext2D,
  plot: Rect,
  area: Rect,
  shape: ChamberShape,
  d: { clears: boolean; majority: number; govSeats: number },
): void {
  const verdict = d.clears ? "MAJORITY" : `HUNG · ${d.majority - d.govSeats} SHORT`;
  const accent = d.clears ? STATUS.good : STATUS.critical;

  // Westminster fills its frame, so the verdict sits between the counts in the
  // header; the arch leaves its centre empty, which is where it belongs there.
  const cx = plot.x + plot.w / 2;
  const cy = shape === "westminster" ? plot.y + PAD + 26 : area.y + area.h - 24;

  ctx.textAlign = "center";
  ctx.font = font(600, 10, "mono");
  const w = ctx.measureText(verdict).width;
  ctx.fillStyle = SURFACE.plot;
  roundRect(ctx, cx - w / 2 - 10, cy - 13, w + 20, 20, 10);
  ctx.fill();
  ctx.fillStyle = alpha(accent, 0.2);
  roundRect(ctx, cx - w / 2 - 8, cy - 11.5, w + 16, 17, 8.5);
  ctx.fill();
  ctx.fillStyle = accent;
  ctx.fillText(verdict, cx, cy + 1);

  ctx.font = font(500, 9, "mono");
  ctx.fillStyle = INK.muted;
  ctx.fillText(`${d.majority} to govern`, cx, cy + 16);
  ctx.textAlign = "left";
}

/**
 * Legend below the chamber. Always present, and every entry carries its seat
 * count and share in text, so identity never rests on colour alone.
 */
function drawLegend(
  ctx: CanvasRenderingContext2D,
  plot: Rect,
  parties: ChamberParty[],
  total: number,
  legendRows: number,
): void {
  const x0 = plot.x + PAD;
  const w = plot.w - PAD * 2;
  const colW = w / LEGEND_COLS;
  const y0 = plot.y + plot.h - PAD - legendRows * LEGEND_ROW_H + LEGEND_ROW_H * 0.72;

  [...parties]
    .sort((a, b) => b.seats - a.seats)
    .forEach((party, i) => {
      const col = i % LEGEND_COLS;
      const row = Math.floor(i / LEGEND_COLS);
      const x = x0 + col * colW;
      const y = y0 + row * LEGEND_ROW_H;

      ctx.fillStyle = ensureVisible(party.color);
      roundRect(ctx, x, y - 7.5, 9, 9, 2.5);
      ctx.fill();

      const share = total > 0 ? ` · ${((party.seats / total) * 100).toFixed(1)}%` : "";
      ctx.font = font(500, TYPE.footer, "mono");
      const metaW = ctx.measureText(`${party.seats}${share}`).width;

      ctx.font = font(500, TYPE.label);
      ctx.fillStyle = INK.primary;
      const name = ellipsize(ctx, party.name, colW - 22 - metaW - 10);
      ctx.fillText(name, x + 15, y);
      const nameW = ctx.measureText(name).width;

      ctx.font = font(500, TYPE.footer, "mono");
      ctx.fillStyle = INK.muted;
      ctx.fillText(`${party.seats}${share}`, x + 15 + nameW + 7, y);
    });
}
