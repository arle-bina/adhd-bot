/**
 * Legislative chamber diagrams — ported from the game.
 *
 * The game already renders both of these (`src/lib/charts/westminsterParliament.ts`
 * and `src/lib/charts/parliamentChart.ts` in AHDGame). This is a port of that
 * code, not a reimplementation, so a chamber in Discord and the same chamber on
 * ahousedividedgame.com are the same picture. If the game's sizing tiers or
 * seating rules change, change them here too.
 *
 * Two shapes, because real chambers have two shapes:
 *
 *   WESTMINSTER — the Commons. Two facing banks of benches with crossbenches
 *          off to one side, generated by `westminster-svg` (the same library
 *          the game uses) and rasterised. Not a hemicycle: the entire point of
 *          the chamber's geometry is that Government and Opposition face each
 *          other across the floor.
 *
 *   ARCH — Congress, the Bundestag, the Dáil, the Diet, the NPC. A hemicycle,
 *          using the game's shared sizing tiers so a 100-seat Senate and a
 *          2,980-seat NPC both fit.
 */

import generate from "westminster-svg";
import { toHtml } from "hast-util-to-html";
import { loadImage, type CanvasRenderingContext2D, type Image } from "canvas";
import { chromeHeight, drawEmptyState, ellipsize, renderCard, roundRect, type CardSpec, type Rect } from "./card.js";
import { font } from "./fonts.js";
import { AXIS, INK, STATUS, SURFACE, TYPE, alpha, ensureVisible } from "./theme.js";

export type ChamberShape = "arch" | "westminster";

export interface ChamberParty {
  name: string;
  seats: number;
  /** The party's own colour. Identity — never assigned by rank. */
  color: string;
}

export interface ChamberOptions extends Omit<CardSpec, "height"> {
  parties: ChamberParty[];
  totalSeats: number;
  /** Seats needed to govern. Defaults to a simple majority. */
  majority?: number;
  shape?: ChamberShape;
  /** Overrides the derived split, when the game knows the actual government. */
  governmentPartyNames?: string[];
  emptyMessage?: string;
}

const PAD = 16;
const LEGEND_ROW_H = 17;
const LEGEND_COLS = 3;
const LEGEND_GAP = 18;
const HEADER_H = 52;
/** The game's vacant-seat grey. */
const VACANT = "#3b3d4d";

// ───────────────────────────────────────────────────────────────────────────
// Hemicycle geometry — ported from AHDGame `src/lib/charts/parliamentSizing.ts`
// ───────────────────────────────────────────────────────────────────────────

export interface ParliamentSizing {
  dotR: number;
  rowGap: number;
  innerR: number;
}

/**
 * Tier sizing, in the game's base 400-unit viewBox. The breakpoints are the
 * game's: the US Senate (100) keeps large dots, the Commons (650) and the
 * Bundestag (736) share a tier, and the NPC (2,980) still fits.
 */
export function getParliamentSizing(total: number): ParliamentSizing {
  if (total <= 110) return { dotR: 7, rowGap: 20, innerR: 55 };
  if (total <= 200) return { dotR: 5, rowGap: 14, innerR: 50 };
  if (total <= 750) return { dotR: 3.4, rowGap: 10, innerR: 45 };
  if (total <= 1500) return { dotR: 2.2, rowGap: 6.5, innerR: 38 };
  return { dotR: 1.6, rowGap: 4.5, innerR: 33 };
}

/** Row-packing loop, ported verbatim so radii match the game's. */
export function computeRowRadii(sizing: ParliamentSizing, total: number): { rowRadii: number[]; outerR: number } {
  const minGap = sizing.dotR * 2.4;
  const rowRadii: number[] = [];
  let totalCap = 0;
  for (let row = 0; totalCap < total; row++) {
    const r = sizing.innerR + row * sizing.rowGap;
    const cap = Math.max(1, Math.floor((Math.PI * r) / minGap));
    rowRadii.push(r);
    totalCap += cap;
  }
  const outerR = rowRadii.length === 0 ? sizing.innerR : rowRadii[rowRadii.length - 1];
  return { rowRadii, outerR };
}

export interface ArchSeat {
  x: number;
  y: number;
  /** 0 at the far left, 1 at the far right. */
  t: number;
}

/**
 * Hemicycle dot positions in the game's 400-unit space, centred on (200, 195).
 * Seats are distributed across rows in proportion to arc length, then sorted
 * left to right — the same order the game seats parties in.
 */
export function archLayout(total: number): { seats: ArchSeat[]; outerR: number } {
  if (total <= 0) return { seats: [], outerR: 0 };

  const sizing = getParliamentSizing(total);
  const { rowRadii, outerR } = computeRowRadii(sizing, total);

  const totalArc = rowRadii.reduce((s, r) => s + Math.PI * r, 0);
  const rowSeats: number[] = [];
  let remaining = total;
  for (let i = 0; i < rowRadii.length; i++) {
    if (i === rowRadii.length - 1) {
      rowSeats.push(remaining);
    } else {
      const n = Math.round(((Math.PI * rowRadii[i]) / totalArc) * total);
      const capped = Math.min(n, remaining);
      rowSeats.push(capped);
      remaining -= capped;
    }
  }

  const seats: ArchSeat[] = [];
  for (let row = 0; row < rowRadii.length; row++) {
    const r = rowRadii[row];
    const n = rowSeats[row];
    for (let i = 0; i < n; i++) {
      const t = n > 1 ? i / (n - 1) : 0.5;
      const angle = Math.PI * (1 - t);
      seats.push({ x: 200 + r * Math.cos(angle), y: 195 - r * Math.sin(angle), t });
    }
  }
  seats.sort((a, b) => a.t - b.t);
  return { seats, outerR };
}

// ───────────────────────────────────────────────────────────────────────────
// Westminster — ported from AHDGame `src/lib/charts/westminsterParliament.ts`
// ───────────────────────────────────────────────────────────────────────────

type WestminsterSide = Record<string, { seats: number; colour: string }>;

export interface WestminsterParliament {
  headBench: WestminsterSide;
  left: WestminsterSide;
  right: WestminsterSide;
  crossBench: WestminsterSide;
}

/**
 * Build the `westminster-svg` parliament object.
 *
 * Government sits on the right, as in the real chamber; the two largest
 * remaining parties form the Opposition on the left; everything else — plus any
 * vacant seats — goes to the crossbenches. That is the game's government-mode
 * seating, applied with the only signal the bot has: seat count.
 */
export function buildWestminsterParliament(
  parties: ChamberParty[],
  totalSeats: number,
  governmentPartyNames?: string[],
): WestminsterParliament {
  const sorted = [...parties].sort((a, b) => b.seats - a.seats);
  const filled = sorted.reduce((s, p) => s + p.seats, 0);
  const vacant = Math.max(0, totalSeats - filled);

  const gov = new Set(
    governmentPartyNames?.length ? governmentPartyNames : sorted.slice(0, 1).map((p) => p.name),
  );
  const government = sorted.filter((p) => gov.has(p.name));
  const rest = sorted.filter((p) => !gov.has(p.name));

  const side = (ps: ChamberParty[]): WestminsterSide =>
    Object.fromEntries(ps.map((p) => [p.name, { seats: p.seats, colour: ensureVisible(p.color) }]));

  const crossBench = side(rest.slice(2));
  if (vacant > 0) crossBench.__vacant__ = { seats: vacant, colour: VACANT };

  return { headBench: {}, left: side(rest.slice(0, 2)), right: side(government), crossBench };
}

/**
 * Rasterise a `westminster-svg` diagram.
 *
 * The library emits a `viewBox` with no width/height, which node-canvas refuses
 * to decode ("Width and height must be set on the svg element"), so the root
 * gets explicit dimensions derived from the viewBox aspect ratio.
 */
export async function renderWestminsterImage(
  parliament: WestminsterParliament,
  width: number,
): Promise<Image | null> {
  try {
    let svg = toHtml(generate(parliament) as never);
    const vb = svg.match(/viewBox="([-\d.,\s]+)"/);
    if (!vb) return null;
    const parts = vb[1].split(/[,\s]+/).map(Number);
    const vw = parts[2];
    const vh = parts[3];
    if (!vw || !vh) return null;
    const height = Math.max(1, Math.round((width * vh) / vw));
    svg = svg.replace("<svg ", `<svg width="${width}" height="${height}" `);
    return await loadImage(Buffer.from(svg));
  } catch {
    return null;
  }
}

/** Split the chamber into its two benches, largest party first. */
export function splitBenches(
  parties: ChamberParty[],
  governmentPartyNames?: string[],
): { government: ChamberParty[]; opposition: ChamberParty[] } {
  const sorted = [...parties].sort((a, b) => b.seats - a.seats);
  if (governmentPartyNames?.length) {
    const gov = new Set(governmentPartyNames);
    return {
      government: sorted.filter((p) => gov.has(p.name)),
      opposition: sorted.filter((p) => !gov.has(p.name)),
    };
  }
  return { government: sorted.slice(0, 1), opposition: sorted.slice(1) };
}

